import { stringify } from 'yaml';
import { compareOrdinal } from '../../model/hash.js';
import type {
  AdapterInput,
  AdapterResult,
  Artifact,
  LoadingEdge,
} from '../../model/types.js';

export function renderKiro(input: AdapterInput): AdapterResult {
  const artifacts: Artifact[] = [],
    loading: LoadingEdge[] = [];
  for (const rule of [...input.rules].sort((a, b) =>
    compareOrdinal(a.id, b.id),
  )) {
    if (
      (rule.targets && !rule.targets.includes(input.target)) ||
      input.sharedRuleIds.includes(rule.id)
    )
      continue;
    const name = rule.id.replace('/', '--');
    const metadata =
      rule.activation.mode === 'files'
        ? {
            inclusion: 'fileMatch',
            fileMatchPattern: [...rule.activation.patterns],
          }
        : rule.activation.mode === 'auto'
          ? { inclusion: 'auto', name, description: rule.description }
          : { inclusion: rule.activation.mode };
    const path = `.kiro/steering/${name}.md`;
    artifacts.push({
      path,
      bytes: new TextEncoder().encode(
        `---\n${stringify(metadata, { lineWidth: 0 })}---\n<!-- Generated by Veritas; source: ${rule.id} -->\n${rule.body}`,
      ),
      executable: false,
      sourceIds: [rule.id],
      consumers: [input.target],
    });
    loading.push({
      consumer: input.target,
      artifactPath: path,
      ruleIds: [rule.id],
    });
  }
  for (const skill of input.skills.filter(
    (skill) => !skill.targets || skill.targets.includes(input.target),
  ))
    for (const file of skill.files)
      artifacts.push({
        ...file,
        path: `.kiro/skills/${skill.name}/${file.path}`,
        bytes: new Uint8Array(file.bytes),
        sourceIds: [skill.source.id],
        consumers: [input.target],
      });
  artifacts.sort((a, b) => compareOrdinal(a.path, b.path));
  return { artifacts, diagnostics: [], loading };
}
