import { stringify } from 'yaml';
import { error } from '../../diagnostics/index.js';
import { compareOrdinal } from '../../model/hash.js';
import type {
  AdapterInput,
  AdapterResult,
  Artifact,
  Diagnostic,
  LoadingEdge,
} from '../../model/types.js';

export function renderClaude(input: AdapterInput): AdapterResult {
  const artifacts: Artifact[] = [],
    diagnostics: Diagnostic[] = [],
    loading: LoadingEdge[] = [];
  if (input.sharedRuleIds.length && input.sharedConsumers.includes('claude')) {
    artifacts.push({
      path: 'CLAUDE.md',
      bytes: new TextEncoder().encode(
        '<!-- Generated by Veritas; shared baseline -->\n@AGENTS.md\n',
      ),
      executable: false,
      sourceIds: [...input.sharedRuleIds],
      consumers: ['claude'],
    });
    loading.push({
      consumer: 'claude',
      artifactPath: 'CLAUDE.md',
      ruleIds: [],
      imports: ['AGENTS.md'],
    });
  }
  for (const rule of [...input.rules].sort((a, b) =>
    compareOrdinal(a.id, b.id),
  )) {
    if (
      (rule.targets && !rule.targets.includes('claude')) ||
      input.sharedRuleIds.includes(rule.id)
    )
      continue;
    if (rule.activation.mode !== 'always' && rule.activation.mode !== 'files') {
      diagnostics.push({
        ...error(
          'ACTIVATION_UNSUPPORTED',
          `Claude cannot preserve ${rule.activation.mode} steering`,
          rule.source,
        ),
        target: 'claude',
      });
      continue;
    }
    const metadata =
      rule.activation.mode === 'files'
        ? `---\n${stringify({ paths: [...rule.activation.patterns] }, { lineWidth: 0 })}---\n`
        : '';
    const path = `.claude/rules/${rule.id.replace('/', '--')}.md`;
    artifacts.push({
      path,
      bytes: new TextEncoder().encode(
        `${metadata}<!-- Generated by Veritas; source: ${rule.id} -->\n${rule.body}`,
      ),
      executable: false,
      sourceIds: [rule.id],
      consumers: ['claude'],
    });
    loading.push({
      consumer: 'claude',
      artifactPath: path,
      ruleIds: [rule.id],
    });
  }
  for (const skill of input.skills.filter(
    (skill) => !skill.targets || skill.targets.includes('claude'),
  ))
    for (const file of skill.files)
      artifacts.push({
        ...file,
        path: `.claude/skills/${skill.name}/${file.path}`,
        bytes: new Uint8Array(file.bytes),
        sourceIds: [skill.source.id],
        consumers: ['claude'],
      });
  artifacts.sort((a, b) => compareOrdinal(a.path, b.path));
  return { artifacts, diagnostics, loading };
}
