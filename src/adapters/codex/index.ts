import { error } from '../../diagnostics/index.js';
import { compareOrdinal } from '../../model/hash.js';
import type {
  AdapterInput,
  AdapterResult,
  Artifact,
  LoadingEdge,
} from '../../model/types.js';

export function renderCodex(input: AdapterInput): AdapterResult {
  const diagnostics = input.rules.flatMap((rule) => {
    if (rule.targets && !rule.targets.includes(input.target)) return [];
    if (rule.activation.mode !== 'always')
      return [
        {
          ...error(
            'ACTIVATION_UNSUPPORTED',
            `Codex cannot preserve ${rule.activation.mode} steering`,
            rule.source,
          ),
          target: input.target,
        },
      ];
    if (!input.sharedRuleIds.includes(rule.id))
      return [
        {
          ...error(
            'ADAPTER_INPUT_INVALID',
            'Codex baseline was not selected by the combined compiler',
            rule.source,
          ),
          target: input.target,
        },
      ];
    return [];
  });
  const artifacts: Artifact[] = input.skills
    .filter((skill) => !skill.targets || skill.targets.includes(input.target))
    .flatMap((skill) =>
      skill.files.map((file) => ({
        ...file,
        path: `.agents/skills/${skill.name}/${file.path}`,
        bytes: new Uint8Array(file.bytes),
        sourceIds: [skill.source.id],
        consumers: [input.target],
      })),
    );
  const loading: LoadingEdge[] = [];
  const shared = input.rules
    .filter(
      (rule) =>
        input.sharedRuleIds.includes(rule.id) &&
        rule.activation.mode === 'always',
    )
    .sort((a, b) => compareOrdinal(a.id, b.id));
  if (shared.length) {
    const text =
      '<!-- Generated by Veritas; outputVersion: 1 -->\n\n' +
      shared
        .map(
          (rule) =>
            `<!-- Generated by Veritas; source: ${rule.id} -->\n${rule.body}${rule.body.endsWith('\n') ? '' : '\n'}`,
        )
        .join('\n');
    artifacts.push({
      path: 'AGENTS.md',
      bytes: new TextEncoder().encode(text),
      executable: false,
      sourceIds: shared.map((rule) => rule.id),
      consumers: [...input.sharedConsumers].sort(compareOrdinal),
    });
    loading.push({
      consumer: 'codex',
      artifactPath: 'AGENTS.md',
      ruleIds: shared.map((rule) => rule.id),
    });
  }
  artifacts.sort((a, b) => compareOrdinal(a.path, b.path));
  return { artifacts, diagnostics, loading };
}
